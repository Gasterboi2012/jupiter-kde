"""Validation and kickstart rendering for the Jupiter text installer.

Everything in this module is side-effect free except ``hash_password``,
which calls ``openssl passwd`` so the plaintext password never ends up in
the kickstart file.
"""

from __future__ import annotations

import re
import subprocess
from dataclasses import dataclass

GPU_DEFAULT = "default"
GPU_NVIDIA = "nvidia"

# Order matters: the GPU screen maps radio-button index -> value.
GPU_CHOICES = (
    (GPU_DEFAULT, "Other GPU (AMD / Intel / default drivers)"),
    (GPU_NVIDIA, "NVIDIA (proprietary open kernel modules: nvidia-open)"),
)

USERNAME_RE = re.compile(r"^[a-z_][a-z0-9_-]{0,31}$")
HOSTNAME_RE = re.compile(r"^(?=.{1,63}$)[a-z0-9]([a-z0-9-]*[a-z0-9])?$")
DISK_RE = re.compile(r"^[A-Za-z0-9_.-]+$")
MIN_PASSWORD_LENGTH = 8

# RPM Fusion release packages; the Fedora release is resolved inside the chroot.
RPMFUSION_FREE = "https://mirrors.rpmfusion.org/free/fedora/rpmfusion-free-release-$(rpm -E %fedora).noarch.rpm"
RPMFUSION_NONFREE = "https://mirrors.rpmfusion.org/nonfree/fedora/rpmfusion-nonfree-release-$(rpm -E %fedora).noarch.rpm"


class ValidationError(ValueError):
    """Raised when a user-entered answer is not acceptable."""


@dataclass
class Answers:
    """Answers collected by the TUI. ``password`` stays in memory only."""

    hostname: str = "jupiter"
    username: str = ""
    password: str = ""
    disk: str = ""
    gpu: str = GPU_DEFAULT

    def summary_lines(self) -> list[str]:
        gpu_label = dict(GPU_CHOICES).get(self.gpu, self.gpu)
        return [
            f"Disk:      /dev/{self.disk} (ALL DATA WILL BE ERASED)",
            f"User:      {self.username} (sudo / wheel)",
            f"Hostname:  {self.hostname}",
            f"Graphics:  {gpu_label}",
        ]


def validate_username(value: str) -> str:
    value = value.strip()
    if not USERNAME_RE.match(value):
        raise ValidationError(
            "Username: 1-32 chars, lowercase letters, digits, '_' or '-', not starting with a digit."
        )
    return value


def validate_hostname(value: str) -> str:
    value = value.strip().lower()
    if not HOSTNAME_RE.match(value):
        raise ValidationError(
            "Hostname: 1-63 chars, letters, digits and inner '-' only."
        )
    return value


def validate_password(password: str, confirm: str) -> None:
    if len(password) < MIN_PASSWORD_LENGTH:
        raise ValidationError(f"Password must be at least {MIN_PASSWORD_LENGTH} characters.")
    if password != confirm:
        raise ValidationError("Passwords do not match.")


def validate_disk(value: str) -> str:
    if not DISK_RE.match(value):
        raise ValidationError(f"Invalid disk name: {value!r}")
    return value


def hash_password(password: str) -> str:
    """Return a SHA-512 crypt hash (``$6$...``) for a kickstart ``--iscrypted`` user."""
    result = subprocess.run(
        ["openssl", "passwd", "-6", "-stdin"],
        input=password,
        text=True,
        capture_output=True,
        check=True,
    )
    return result.stdout.strip()


# Shared by the installed system: theme the boot splash and keep the
# Jupiter-branded os-release. Runs inside the installed chroot.
COMMON_POST = """\
# Make the Jupiter boot splash the default and rebuild the initramfs with it.
plymouth-set-default-theme -R jupiter || true
"""

NVIDIA_POST = f"""\
# NVIDIA proprietary open kernel modules from RPM Fusion (akmod builds on boot).
dnf -y install "{RPMFUSION_FREE}" "{RPMFUSION_NONFREE}"
dnf -y install akmod-nvidia-open
grubby --update-kernel=ALL --args="nvidia-drm.modeset=1"
"""


def render_kickstart(answers: Answers, password_hash: str) -> str:
    """Render the install kickstart for the given answers.

    Raises ValidationError if any answer is malformed, so a bad value can
    never reach Anaconda.
    """
    username = validate_username(answers.username)
    hostname = validate_hostname(answers.hostname)
    disk = validate_disk(answers.disk)
    if answers.gpu not in dict(GPU_CHOICES):
        raise ValidationError(f"Unknown graphics choice: {answers.gpu!r}")
    if not password_hash.startswith("$6$"):
        raise ValidationError("Password hash must be a SHA-512 crypt hash.")

    post = COMMON_POST
    if answers.gpu == GPU_NVIDIA:
        post += "\n" + NVIDIA_POST

    return f"""\
# Generated by jupiter-installer. Re-run the installer instead of editing by hand.
lang en_US.UTF-8
keyboard --xlayouts='us'
timezone UTC --utc
network --bootproto=dhcp --device=link --activate --onboot=yes --hostname={hostname}

# Target disk: only this disk is touched.
ignoredisk --only-use={disk}
clearpart --all --initlabel --drives={disk}
autopart --type=btrfs

rootpw --lock
user --name={username} --groups=wheel --iscrypted --password={password_hash}

selinux --enforcing
firewall --enabled
services --enabled=NetworkManager,sddm

reboot --eject

%post --log=/var/log/jupiter-post.log
{post}%end
"""
